const hash = (s: string): number => {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
  return h;
};

/** Deterministic per local day, so a retried briefing shows the same riddle. */
export function dayRiddle(day: string): { question: string; answer: string } {
  const [question, answer] = RIDDLES[hash("riddle:" + day) % RIDDLES.length];
  return { question, answer };
}

